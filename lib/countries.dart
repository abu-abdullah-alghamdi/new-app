/// مفتاح الترتيب: نتجاهل "ال" في البداية ونوحّد أشكال الألف
String _sortKey(String name) {
  var n = name;
  if (n.startsWith('ال')) n = n.substring(2);
  return n.replaceAll(RegExp('[أإآ]'), 'ا').replaceAll('ُ', '');
}

/// يوحّد النص للبحث (بدون همزات ولا تشكيل)
String searchKey(String s) => s
    .replaceAll(RegExp('[أإآ]'), 'ا')
    .replaceAll('ة', 'ه')
    .replaceAll('ى', 'ي')
    .replaceAll(RegExp('[ً-ْ]'), '')
    .trim();

final List<String> countries = [
  saudiArabia,
  ...([..._others]..sort((a, b) => _sortKey(a).compareTo(_sortKey(b)))),
